import uuid
from typing import List, Dict, Any, Optional
import ollama
from qdrant_client import QdrantClient, models
from core.config import (
    QDRANT_HOST,
    QDRANT_PORT,
    QDRANT_COLLECTION,
    EMBEDDING_MODEL,
    EMBEDDING_OPTIONS
)

VECTOR_SIZE = 768  # embeddinggemma-2:latest dimension

class VectorStore:
    def __init__(
        self,
        host: str = QDRANT_HOST,
        port: int = QDRANT_PORT,
        collection_name: str = QDRANT_COLLECTION,
        embedding_model: str = EMBEDDING_MODEL,
        embedding_options: dict = EMBEDDING_OPTIONS
    ):
        self.host = host
        self.port = port
        self.collection_name = collection_name
        self.embedding_model = embedding_model
        self.embedding_options = embedding_options
        self.ollama_client = ollama.Client()
        self.client = QdrantClient(host=self.host, port=self.port, timeout=30.0)
        self._ensure_collection()

    def _ensure_collection(self):
        """Ensures that the Qdrant collection exists with the proper dimension."""
        if not self.client.collection_exists(self.collection_name):
            self.client.create_collection(
                collection_name=self.collection_name,
                vectors_config=models.VectorParams(
                    size=VECTOR_SIZE,
                    distance=models.Distance.COSINE
                )
            )

    def get_embedding(self, text: str) -> List[float]:
        """
        Generates text embedding using embeddinggemma-2:latest.
        MANDATORY CONSTRAINT: options={'num_gpu': 0} to run strictly on CPU/RAM.
        """
        # Ensure non-empty text
        clean_text = text.strip() or "documento"
        # Truncate very long texts to fit embedding window safely
        clean_text = clean_text[:4000]

        response = self.ollama_client.embeddings(
            model=self.embedding_model,
            prompt=clean_text,
            options=self.embedding_options
        )
        return response["embedding"]

    def upsert_text_chunks(self, chunks: List[Dict[str, Any]], batch_size: int = 16):
        """
        Embeds and stores text chunks in Qdrant with metadata (including audio/video timestamps).
        """
        if not chunks:
            return

        points = []
        for chunk in chunks:
            text = chunk["content"]
            vector = self.get_embedding(text)
            
            point_id = str(uuid.uuid5(uuid.NAMESPACE_DNS, chunk["chunk_id"]))
            payload = {
                "doc_name": chunk["doc_name"],
                "chunk_id": chunk["chunk_id"],
                "page_number": chunk.get("page_number", 1),
                "start_time": chunk.get("start_time", 0.0),
                "end_time": chunk.get("end_time", 0.0),
                "timestamp_label": chunk.get("timestamp_label", ""),
                "media_type": chunk.get("media_type", "pdf"),
                "source_type": chunk.get("source_type", "text"),
                "visual_category": chunk.get("visual_category", "None"),
                "content": text,
                "image_path": chunk.get("image_path", "")
            }
            points.append(models.PointStruct(id=point_id, vector=vector, payload=payload))

            if len(points) >= batch_size:
                self.client.upsert(collection_name=self.collection_name, points=points)
                points = []

        if points:
            self.client.upsert(collection_name=self.collection_name, points=points)

    def upsert_visual_element(
        self,
        doc_name: str,
        element_id: str,
        page_number: int,
        visual_category: str,
        description: str,
        transcription: str,
        image_path: str,
        start_time: float = 0.0,
        end_time: float = 0.0,
        timestamp_label: str = "",
        media_type: str = "image"
    ):
        """
        Embeds the visual comprehension generated by Qwen2.5-VL and stores it in Qdrant.
        Supports page numbers (PDF) or timestamps (video frames).
        """
        # Rich text synthesis for embedding matching
        loc_str = f"En lapso {timestamp_label}" if timestamp_label else f"En página {page_number}"
        combined_content = f"[{visual_category.upper()}] {loc_str}.\n"
        if transcription:
            combined_content += f"Texto visible y datos: {transcription}\n"
        combined_content += f"Descripción visual: {description}"

        vector = self.get_embedding(combined_content)
        point_id = str(uuid.uuid5(uuid.NAMESPACE_DNS, element_id))

        payload = {
            "doc_name": doc_name,
            "element_id": element_id,
            "page_number": page_number,
            "start_time": start_time,
            "end_time": end_time,
            "timestamp_label": timestamp_label,
            "media_type": media_type,
            "source_type": "visual",
            "visual_category": visual_category,
            "content": combined_content,
            "transcription": transcription,
            "description": description,
            "image_path": str(image_path)
        }

        self.client.upsert(
            collection_name=self.collection_name,
            points=[models.PointStruct(id=point_id, vector=vector, payload=payload)]
        )

    def search(
        self,
        query: str,
        doc_name: Optional[str] = None,
        doc_names: Optional[List[str]] = None,
        limit: int = 5,
        source_type: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Vector search on Qdrant using embeddinggemma-2:latest query vector.
        Supports filtering by one or multiple documents associated with a chat.
        """
        query_vector = self.get_embedding(query)

        # Normalize document names filter
        target_docs = []
        if doc_names:
            target_docs.extend(doc_names)
        elif doc_name:
            target_docs.append(doc_name)

        conditions = []
        if target_docs:
            if len(target_docs) == 1:
                conditions.append(
                    models.FieldCondition(
                        key="doc_name",
                        match=models.MatchValue(value=target_docs[0])
                    )
                )
            else:
                conditions.append(
                    models.FieldCondition(
                        key="doc_name",
                        match=models.MatchAny(any=target_docs)
                    )
                )

        if source_type:
            conditions.append(
                models.FieldCondition(
                    key="source_type",
                    match=models.MatchValue(value=source_type)
                )
            )

        query_filter = None
        if conditions:
            query_filter = models.Filter(must=conditions)

        res = self.client.query_points(
            collection_name=self.collection_name,
            query=query_vector,
            limit=limit,
            query_filter=query_filter
        )

        results = []
        for p in res.points:
            payload = p.payload or {}
            results.append({
                "score": p.score,
                "content": payload.get("content", ""),
                "page_number": payload.get("page_number", 0),
                "start_time": payload.get("start_time", 0.0),
                "end_time": payload.get("end_time", 0.0),
                "timestamp_label": payload.get("timestamp_label", ""),
                "media_type": payload.get("media_type", "pdf"),
                "source_type": payload.get("source_type", "text"),
                "visual_category": payload.get("visual_category", "None"),
                "image_path": payload.get("image_path", ""),
                "element_id": payload.get("element_id", payload.get("chunk_id", "")),
                "doc_name": payload.get("doc_name", "")
            })

        return results

    def delete_document_points(self, doc_name: str):
        """Removes existing points for a document to allow clean re-indexing."""
        self.client.delete(
            collection_name=self.collection_name,
            points_selector=models.FilterSelector(
                filter=models.Filter(
                    must=[
                        models.FieldCondition(
                            key="doc_name",
                            match=models.MatchValue(value=doc_name)
                        )
                    ]
                )
            )
        )

    def delete_all_points(self):
        """Clears all vectors in the collection."""
        if self.client.collection_exists(self.collection_name):
            self.client.delete_collection(self.collection_name)
            self._ensure_collection()
